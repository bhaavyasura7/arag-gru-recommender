"""Write configs/categories/<Category>.yaml: the base config with every output path namespaced.

Nothing written by a category run touches the Video Games artifacts or results/. Use it with
ARAG_CONFIG, e.g.

    .venv/bin/python scripts/make_category_config.py Electronics
    ARAG_CONFIG=configs/categories/Electronics.yaml make data lists index gru gru-text eval report verify

Deviations from the Video Games run (recorded in the file itself): a seeded 100K-user subsample,
metadata restricted to interacted items, the ID-only GRU fixed to its Video Games best config,
theta fixed to its Video Games value, and NVIDIA Nemotron 3 Super 120B (free NVIDIA API) as the LLM; Ultra 550B was tried but is capacity-limited on the free tier.
"""
from __future__ import annotations

import copy
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent

OVERRIDES = {
    "dataset": {"max_users": 100_000, "items_scope": "interacted"},
    "llm": {"provider": "nvidia", "model": "nvidia/nemotron-3-super-120b-a12b", "timeout_s": 180, "concurrency": 4},
    "agents": {"theta_grid": [5]},
    "gru": {"hidden_grid": [128], "dropout_grid": [0.2], "device": "auto"},
    "app": {"gru_variant": "text"},
    "budget": {"prices": {"input_per_1m": 0.0, "output_per_1m": 0.0}},  # free NVIDIA API
}


def deep_update(base: dict, upd: dict) -> dict:
    for k, v in upd.items():
        if isinstance(v, dict) and isinstance(base.get(k), dict):
            deep_update(base[k], v)
        else:
            base[k] = v
    return base


def main(category: str) -> Path:
    base = yaml.safe_load((ROOT / "configs" / "config.yaml").read_text())
    cfg = copy.deepcopy(base)
    cfg["dataset"]["category"] = category
    deep_update(cfg, OVERRIDES)
    ns = {
        "data_raw": f"data/{category}/raw",
        "data_processed": f"data/{category}/processed",
        "artifacts": f"artifacts/{category}",
        "lists": f"artifacts/{category}/lists",
        "gru": f"artifacts/{category}/gru",
        "gru_text": f"artifacts/{category}/gru_text",
        "faiss": f"artifacts/{category}/faiss",
        "llm_cache": f"artifacts/{category}/llm_cache",
        "predictions": f"artifacts/{category}/predictions",
        "app_db": f"artifacts/{category}/app.db",
        "results": f"results/categories/{category}",
        "predictions_csv": f"results/categories/{category}/predictions",
    }
    missing = set(cfg["paths"]) - set(ns) - {"prompts"}
    if missing:
        raise SystemExit(f"unmapped path keys would be shared with Video Games: {sorted(missing)}")
    cfg["paths"].update(ns)
    out = ROOT / "configs" / "categories" / f"{category}.yaml"
    out.parent.mkdir(parents=True, exist_ok=True)
    header = (
        f"# {category}: generated by scripts/make_category_config.py from configs/config.yaml.\n"
        "# All outputs are namespaced; deviations vs Video Games: 100K-user subsample, metadata for\n"
        "# interacted items only, GRU config fixed to the Video Games best (128/0.2), theta fixed to 5,\n"
        "# LLM = NVIDIA Nemotron 3 Super 120B (nvidia/nemotron-3-super-120b-a12b) via the NVIDIA API.\n"
    )
    out.write_text(header + yaml.safe_dump(cfg, sort_keys=False))
    print("wrote", out.relative_to(ROOT))
    return out


if __name__ == "__main__":
    for c in sys.argv[1:] or ["Electronics"]:
        main(c)
